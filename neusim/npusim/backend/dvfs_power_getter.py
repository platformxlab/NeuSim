@lru_cache(maxsize=None)
def get_power_from_dvfs(component: str, dvfs: ComponentDVFSConfig) -> tuple[float, float]:
    """
    Compute (dynamic_power_W, static_power_W) for a component from DVFSConfig.

    ``HBM`` and ``ICI`` retain the pre-split public API meaning: their results
    are the sums of all currently modeled HBM or ICI domains.  Internal model
    code should query the lower-case split names so each domain is accounted
    for exactly once.  A legacy aggregate V/f request is applied to every split
    lookup; each split table then enforces its own voltage/bandwidth rules.
    """
    comp = _normalize_component(component)

    if comp in AGGREGATE_POWER_COMPONENTS:
        total_dynamic_power_W = 0.0
        total_static_power_W = 0.0
        for split_component in AGGREGATE_POWER_COMPONENTS[comp]:
            dynamic_power_W, static_power_W = get_power_from_dvfs(
                split_component, dvfs
            )
            total_dynamic_power_W += dynamic_power_W
            total_static_power_W += static_power_W
        return total_dynamic_power_W, total_static_power_W

    v_req = dvfs.voltage_V
    f_req_GHz = dvfs.frequency_GHz

    # default No DVFS policy: use max performance point (peak voltage and freq/bandwidth)
    if dvfs.policy == DVFSPolicy.NONE or (
        (v_req is None or v_req <= 0.0)
        and (f_req_GHz is None or f_req_GHz <= 0.0)
    ):
        max_point = _max_perf_point(comp)
        return max_point.dynamic_power_W, max_point.static_power_W

    # SA / VU / SRAM: use frequency in GHz
    if comp in ("sa", "vu", "sram"):
        points = SA_POINTS if comp == "sa" else VU_POINTS if comp == "vu" else SRAM_POINTS
        base_freq_ghz = _baseline_freq_ghz(points)

        if f_req_GHz is None or f_req_GHz <= 0.0:
            f_req_GHz = base_freq_ghz

        # first find the nearest voltage corner
        groups = _group_by_voltage(points)
        _, rows = _choose_voltage_by_request_or_range(groups, f_req_GHz, v_req)
        assert rows is not None, f"No voltage rows available for {comp} selection."
        x_ref, s_ref, d_ref = _nearest_point(rows, f_req_GHz)

        # then extrapolate the dynamic power from the existing corners using the given target frequency (Dynamic Power ~ freq)
        dyn = _scale_dynamic(d_ref, x_ref, f_req_GHz)
        static = s_ref
        return dyn, static

    # HBM / ICI: map DVFS freq proxy to bandwidth
    if comp in ("hbm_mc", "hbm_phy", "hbm_die", "hbm_io", "ici_mc", "ici_phy"):
        is_hbm_family = comp in ("hbm_mc", "hbm_phy", "hbm_die", "hbm_io")
        base_bw = _baseline_bw_hbm() if is_hbm_family else _baseline_bw_ici()
        base_freq_ghz = 1.7
        if comp == "hbm_mc":
            points = HBM_MC_POINTS
        elif comp == "hbm_phy":
            points = HBM_PHY_POINTS
        elif comp == "hbm_die":
            points = HBM_DIE_POINTS
        elif comp == "hbm_io":
            points = HBM_IO_POINTS
        elif comp == "ici_mc":
            points = ICI_MC_POINTS
        elif comp == "ici_phy":
            points = ICI_PHY_POINTS

        if f_req_GHz is not None and f_req_GHz > 0.0:
            bw_target = base_bw * (f_req_GHz / base_freq_ghz)
        else:
            bw_target = base_bw

        # group by voltage: {v: [(bw, s, d), ...]}
        groups: Groups = {}
        for v, bw, st_p, dyn_p in points:
            groups.setdefault(v, []).append(Row(bw, st_p, dyn_p))
        for v in groups:
            groups[v].sort(key=lambda t: t.x)

        _, rows = _choose_voltage_by_request_or_range(groups, bw_target, v_req)
        assert rows is not None, f"No voltage rows available for {comp} selection."
        bw_ref, s_ref, d_ref = _nearest_point(rows, bw_target)

        dyn = _scale_dynamic(d_ref, bw_ref, bw_target)
        static = s_ref
        return dyn, static

    raise ValueError(f"Unsupported component: {component!r}")


@lru_cache(maxsize=None)
def get_all_dvfs_configs_for_component(
    component: str,
    policy: DVFSPolicy = DVFSPolicy.IDEAL,
) -> list[ComponentDVFSConfig]:
    """
    Return all possible DVFS configurations for a given component.
    """
    comp = _normalize_component(component)
    # Unlike power queries, legacy HBM/ICI configuration requests describe the
    # digital-controller proxy.  Keep that search cardinality and CSV behavior
    # independent from aggregate power-query compatibility.
    comp = _LEGACY_CONFIG_COMPONENT_ALIASES.get(comp, comp)
    configs: list[ComponentDVFSConfig] = []

    # Use 20ns scaling time for IDEAL DVFS (most power-efficient regulator setting),
    # matching get_dvfs_policy_Ideal(). IDEAL policy later will ignore scaling time overhead,
    # so the longer scaling time has no time penalty.
    scaling_time_ns = 20

    if comp in ("sa", "vu", "sram"):
        points = SA_POINTS if comp == "sa" else VU_POINTS if comp == "vu" else SRAM_POINTS
        for v, f, s, d in points:
            configs.append(
                ComponentDVFSConfig(
                    policy=policy,
                    voltage_V=v,
                    frequency_GHz=f,
                    voltage_regulator_scaling_time_ns=scaling_time_ns,
                )
            )
        return configs

    if comp in ("hbm_mc", "hbm_phy", "hbm_die", "hbm_io", "ici_mc", "ici_phy"):
        is_hbm_family = comp in ("hbm_mc", "hbm_phy", "hbm_die", "hbm_io")
        if comp == "hbm_mc":
            points = HBM_MC_POINTS
        elif comp == "hbm_phy":
            points = HBM_PHY_POINTS
        elif comp == "hbm_die":
            points = HBM_DIE_POINTS
        elif comp == "hbm_io":
            points = HBM_IO_POINTS
        elif comp == "ici_mc":
            points = ICI_MC_POINTS
        elif comp == "ici_phy":
            points = ICI_PHY_POINTS
        for v, bw, s, d in points:
            # Map bandwidth back to frequency proxy
            base_bw = _baseline_bw_hbm() if is_hbm_family else _baseline_bw_ici()
            base_freq_ghz = 1.7
            f = base_freq_ghz * (bw / base_bw)
            configs.append(
                ComponentDVFSConfig(
                    policy=policy,
                    voltage_V=v,
                    frequency_GHz=f,
                    voltage_regulator_scaling_time_ns=scaling_time_ns,
                )
            )
        return configs

    raise ValueError(f"Unsupported component: {component!r}")


def _balanced_cartesian_counts(
    lengths: Sequence[int],
    max_product: int,
) -> list[int]:
    """Choose balanced per-domain counts whose product is at most the cap.

    Singleton domains remain singletons. Every other domain keeps at least two
    points so its first and last V/f states can be retained. Counts are scaled
    proportionally, then spare product capacity is assigned to the domain with
    the smallest retained fraction (source-order index breaks ties).
    """
    if max_product < 1:
        raise ValueError("max_product must be positive")
    if any(length < 1 for length in lengths):
        raise ValueError("all Cartesian dimensions must be non-empty")

    original = [int(length) for length in lengths]
    if math.prod(original) <= max_product:
        return original

    minimum = [1 if length == 1 else 2 for length in original]
    if math.prod(minimum) > max_product:
        raise ValueError(
            "max_product is too small to preserve both endpoints of every "
            "non-singleton Cartesian dimension"
        )

    active = [index for index, length in enumerate(original) if length > 1]
    scale = (max_product / math.prod(original)) ** (1.0 / len(active))
    counts = [
        max(minimum[index], min(length, math.floor(length * scale)))
        for index, length in enumerate(original)
    ]

    # Floating-point rounding or minimum endpoint constraints can leave the
    # first estimate just above the cap. Remove one point at a time from the
    # most over-represented domain until it is valid.
    while math.prod(counts) > max_product:
        candidates = [
            index
            for index in active
            if counts[index] > minimum[index]
        ]
        index = max(
            candidates,
            key=lambda item: (counts[item] / original[item], -item),
        )
        counts[index] -= 1

    # Fill remaining capacity as evenly as possible without crossing the cap.
    while True:
        current_product = math.prod(counts)
        candidates = [
            index
            for index in active
            if counts[index] < original[index]
            and current_product // counts[index] * (counts[index] + 1)
            <= max_product
        ]
        if not candidates:
            break
        index = min(
            candidates,
            key=lambda item: (counts[item] / original[item], item),
        )
        counts[index] += 1

    return counts


def _evenly_sample_by_frequency(
    values: Sequence[ComponentDVFSConfig],
    count: int,
) -> list[ComponentDVFSConfig]:
    """Return frequency-ordered samples that preserve true V/f endpoints."""
    if not 1 <= count <= len(values):
        raise ValueError("count must be between one and the sequence length")
    ordered = sorted(
        values,
        key=lambda config: (
            float(config.frequency_GHz or 0.0),
            float(config.voltage_V or 0.0),
        ),
    )
    if count == len(ordered):
        return ordered
    if count == 1:
        return [ordered[0]]
    last = len(ordered) - 1
    denominator = count - 1
    indices = [index * last // denominator for index in range(count)]
    return [ordered[index] for index in indices]


def iter_all_dvfs_configs_for_op(
    op: Operator.Operator,
    policy: DVFSPolicy = DVFSPolicy.IDEAL,
    perf_degrade_threshold: float = 0,
    total_exe_time_ns: float | None = None,
) -> Iterator[dict[str, ComponentDVFSConfig]]:
    """
    Lazily yield all possible DVFS configurations for the given operator.

    Enumeration order is identical to ``get_all_dvfs_configs_for_op``. The
    lazy API is used by exhaustive Ideal search so a large Cartesian product
    does not have to be resident in memory before candidate analysis starts.
    Sweeps through all frequencies for each component and pick the lowest voltage accordingly.
    If the component is unused, just set it to the lowest power state.
    - policy: DVFSPolicy to use for filling out ComponentDVFSConfig.
    - perf_degrade_threshold: float, maximum allowed performance degradation for the entire workload.
    """
    logging.set_verbosity(logging.INFO)

    # Only sweep DVFS-able components; PHY/die/io sub-components always run at fixed voltage.
    comp_names = ("sa", "vu", "sram", "hbm_mc", "ici_mc")
    # Fixed config for non-DVFS-able sub-components
    phy_fixed_config = ComponentDVFSConfig(
        policy=DVFSPolicy.NONE, voltage_V=0.7, frequency_GHz=1.7,
        voltage_regulator_scaling_time_ns=0,
    )

    def _get_exe_time_ns(comp_name: str) -> float:
        if comp_name == "sa":
            return op.stats.sa_time_ns
        elif comp_name == "vu":
            return op.stats.vu_time_ns
        elif comp_name == "sram":
            return op.stats.vmem_time_ns
        elif comp_name == "hbm_mc":
            return op.stats.memory_time_ns
        elif comp_name == "ici_mc":
            return op.stats.ici_time_ns
        else:
            raise ValueError(f"Unsupported component name: {comp_name!r}")

    # 1. Compute max allowed execution time
    #    max_allowed_exe_time_ns is derived from the perf_degrade_threshold and the program's original execution time.
    #    If total_exe_time_ns is not provided, use op.stats.execution_time_ns as the baseline.
    if not total_exe_time_ns:
        total_exe_time_ns = op.stats.execution_time_ns
    max_slack_time_ns = total_exe_time_ns * perf_degrade_threshold
    max_allowed_exe_time_ns = op.stats.execution_time_ns + max_slack_time_ns / op.stats.count

    logging.info(f"op_name: {op.name}, original_exe_time_ns: {op.stats.execution_time_ns}, max_allowed_exe_time_ns: {max_allowed_exe_time_ns}, max_op_perf_degrade: {(max_allowed_exe_time_ns / op.stats.execution_time_ns - 1) * 100:.4f}%")

    # 2. For each component, generate all ComponentDVFSConfigs and filter by
    #    min_freq based on the performance budget. We keep all V/F points
    #    (not just max-freq-per-voltage) because VR efficiency depends on
    #    activity factor, and intermediate frequencies at the same voltage
    #    can yield lower total energy. If the resulting search space exceeds
    #    MAX_CONFIGS, fall back to max+min-per-voltage reduction.
    # Use 20ns scaling time for IDEAL DVFS (most power-efficient regulator setting),
    # matching get_dvfs_policy_Ideal(). IDEAL policy ignores execution time overhead.
    scaling_time_ns = 20
    comp_configs_list: list[list[ComponentDVFSConfig]] = []  # list of ComponentDVFSConfigs for each component
    for comp_name in comp_names:
        exe_time_ns = _get_exe_time_ns(comp_name)

        if exe_time_ns > 0:
            all_cfgs = get_all_dvfs_configs_for_component(comp_name, policy)

            # Apply min_freq_allowed as lower bound (based on max_allowed_exe_time_ns).
            # must have component exe time <= max_allowed_exe_time_ns
            slowdown_factor_min = exe_time_ns / max_allowed_exe_time_ns
            comp_points = {"sa": SA_POINTS, "vu": VU_POINTS, "sram": SRAM_POINTS}
            min_freq_GHz_allowed = max(
                (
                    _baseline_freq_ghz(comp_points[comp_name]) * slowdown_factor_min
                    if comp_name in ("sa", "vu", "sram")
                    else 1.7 * slowdown_factor_min  # for HBM MC and ICI MC
                ) - 0.05,  # step size is 0.05 GHz
                0,
            )
            all_cfgs = [
                cfg for cfg in all_cfgs
                if cfg.frequency_GHz >= min_freq_GHz_allowed
            ]
            assert len(all_cfgs) > 0, f"No valid DVFS configs for component {comp_name!r} (min_freq {min_freq_GHz_allowed:.4f} GHz)"
            comp_configs_list.append(all_cfgs)
        else:
            min_power_point = _min_power_point(comp_name)
            comp_configs_list.append([
                ComponentDVFSConfig(
                    policy=policy,
                    voltage_V=min_power_point.voltage_V,
                    frequency_GHz=0.05,  # assume lowest freq is 0.05 GHz for now
                    voltage_regulator_scaling_time_ns=scaling_time_ns,
                )
            ])

    # If the search space is too large, fall back to max+min-per-voltage reduction.
    raw_counts = [len(configs) for configs in comp_configs_list]
    raw_product = math.prod(raw_counts)
    if raw_product > MAX_EXHAUSTIVE_DVFS_CONFIGS:
        for i, cfgs in enumerate(comp_configs_list):
            if len(cfgs) <= 2:
                continue
            voltage_to_max: dict[float, ComponentDVFSConfig] = {}
            voltage_to_min: dict[float, ComponentDVFSConfig] = {}
            for cfg in cfgs:
                v = cfg.voltage_V
                if v not in voltage_to_max or cfg.frequency_GHz > voltage_to_max[v].frequency_GHz:
                    voltage_to_max[v] = cfg
                if v not in voltage_to_min or cfg.frequency_GHz < voltage_to_min[v].frequency_GHz:
                    voltage_to_min[v] = cfg
            kept: dict[tuple[float, float], ComponentDVFSConfig] = {}
            for v in voltage_to_max:
                kept[(v, voltage_to_max[v].frequency_GHz)] = voltage_to_max[v]
                kept[(v, voltage_to_min[v].frequency_GHz)] = voltage_to_min[v]
            comp_configs_list[i] = list(kept.values())
        logging.info(
            "op %s: search space %d > %d, per-voltage extrema reduce it to %d",
            op.name,
            raw_product,
            MAX_EXHAUSTIVE_DVFS_CONFIGS,
            math.prod(len(configs) for configs in comp_configs_list),
        )

    extrema_counts = [len(configs) for configs in comp_configs_list]
    extrema_product = math.prod(extrema_counts)
    balanced_cap_applied = (
        policy == DVFSPolicy.IDEAL
        and extrema_product > MAX_EXHAUSTIVE_DVFS_CONFIGS
    )
    if balanced_cap_applied:
        final_counts = _balanced_cartesian_counts(
            extrema_counts,
            MAX_EXHAUSTIVE_DVFS_CONFIGS,
        )
        comp_configs_list = [
            _evenly_sample_by_frequency(configs, count)
            for configs, count in zip(
                comp_configs_list,
                final_counts,
                strict=True,
            )
        ]
        logging.info(
            "op %s: endpoint-preserving balanced cap reduces per-domain "
            "counts %s to %s (%d candidates)",
            op.name,
            extrema_counts,
            final_counts,
            math.prod(final_counts),
        )
    else:
        final_counts = extrema_counts

    final_product = math.prod(final_counts)
    iter_all_dvfs_configs_for_op.last_stats = {
        "domain_names": list(comp_names),
        "raw_domain_counts_after_budget_filter": raw_counts,
        "raw_product_after_budget_filter": raw_product,
        "per_voltage_extrema_reduction_applied": (
            raw_product > MAX_EXHAUSTIVE_DVFS_CONFIGS
        ),
        "domain_counts_after_voltage_extrema": extrema_counts,
        "product_after_voltage_extrema": extrema_product,
        "balanced_endpoint_cap_applied": balanced_cap_applied,
        "final_domain_counts": final_counts,
        "final_candidate_product": final_product,
        "maximum_candidate_product": MAX_EXHAUSTIVE_DVFS_CONFIGS,
        "balanced_cap_semantics": (
            "proportional per-domain counts with deterministic frequency-ordered "
            "even samples that preserve each non-singleton domain V/f endpoint; "
            "capped enumeration order is frequency then voltage"
        ),
    }

    num_configs = 0
    for combo in itertools.product(*comp_configs_list):  # combo: (sa, vu, sram, hbm_mc, ici_mc) ComponentDVFSConfig
        config_dict = {comp_name: config for comp_name, config in zip(comp_names, combo)}

        if policy in (DVFSPolicy.CUSTOM_ALL, DVFSPolicy.CUSTOM_ALL_ms, DVFSPolicy.IDEAL):
            # Couple HBM Die and IO Link to the same bandwidth as HBM MC.
            # MC freq → bandwidth → look up Die@1.2V and IO at that bandwidth.
            hbm_mc_cfg = config_dict["hbm_mc"]
            mc_freq = hbm_mc_cfg.frequency_GHz or 1.7
            hbm_base_bw = _baseline_bw_hbm()
            target_bw = hbm_base_bw * (mc_freq / 1.7)

            die_policy = DVFSPolicy.CUSTOM if policy in (DVFSPolicy.CUSTOM_ALL, DVFSPolicy.CUSTOM_ALL_ms) else DVFSPolicy.IDEAL

            # HBM Die at 1.2V: find nearest bandwidth point
            die_at_v = [p for p in HBM_DIE_POINTS if abs(p.voltage_V - 1.2) < 0.02]
            if die_at_v:
                die_bws = sorted(die_at_v, key=lambda p: p.bandwidth_GBs)
                # Find nearest BW >= target, or the max
                die_point = die_bws[-1]
                for p in die_bws:
                    if p.bandwidth_GBs >= target_bw - 1:
                        die_point = p
                        break
                config_dict["hbm_die"] = ComponentDVFSConfig(
                    policy=die_policy, voltage_V=die_point.voltage_V,
                    frequency_GHz=mc_freq,
                    voltage_regulator_scaling_time_ns=0,
                )
            else:
                config_dict["hbm_die"] = phy_fixed_config

            # HBM IO Link: find nearest bandwidth point (V/f scaled)
            io_bws = sorted(HBM_IO_POINTS, key=lambda p: p.bandwidth_GBs)
            io_point = io_bws[-1]
            for p in io_bws:
                if p.bandwidth_GBs >= target_bw - 1:
                    io_point = p
                    break
            config_dict["hbm_io"] = ComponentDVFSConfig(
                policy=die_policy, voltage_V=io_point.voltage_V,
                frequency_GHz=mc_freq,
                voltage_regulator_scaling_time_ns=0,
            )
        else:
            # Non-DVFS-able sub-components always fixed
            config_dict["hbm_die"] = phy_fixed_config
            config_dict["hbm_io"] = phy_fixed_config

        config_dict["ici_phy"] = phy_fixed_config
        num_configs += 1
        yield config_dict

    logging.info(f"Total DVFS configurations generated for op {op.name}: {num_configs}")


def get_all_dvfs_configs_for_op(
    op: Operator.Operator,
    policy: DVFSPolicy = DVFSPolicy.IDEAL,
    perf_degrade_threshold: float = 0,
    total_exe_time_ns: float | None = None,
) -> list[dict[str, ComponentDVFSConfig]]:
    """Return the lazy per-operator DVFS enumeration as a compatibility list."""

    return list(
        iter_all_dvfs_configs_for_op(
            op,
            policy,
            perf_degrade_threshold,
            total_exe_time_ns,
        )
    )
