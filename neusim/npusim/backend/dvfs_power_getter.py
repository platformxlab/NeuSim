"""
Map DVFSConfig (policy, voltage_V, frequency_GHz) to dynamic/static power
using discrete SA/VU/SRAM/HBM/ICI tables.

Key rules:
- Baseline freq/bw is the max value in each table (fixed).
- If policy == NONE or both voltage_V and frequency_GHz are None:
    use the baseline operating point for that component.
- For SA/VU/SRAM:
    * Use dvfs.frequency_GHz as target frequency (GHz).
    * Choose voltage segment either:
        - closest to dvfs.voltage_V if provided, or
        - inferred from freq range if voltage_V is None.
    * In that segment, pick nearest table point.
    * Dynamic power scales linearly with freq at the same voltage.
    * Static power = static_power_W of the nearest point (voltage dependent).
- For HBM/ICI:
    * Use dvfs.frequency_GHz as a proxy to scale bandwidth from baseline:
        bw_target = bw_base * (f_dvfs / f_base).
      If frequency_GHz is None, use bw_base.
    * Dynamic scales linearly with BW; static from nearest row.
"""

# Type aliases for table structures
class VfPoint(NamedTuple):
    '''Voltage/frequency point for SA/VU/SRAM components.'''
    voltage_V: float = 0.7
    frequency_GHz: float = 1.7
    static_power_W: float = 0.0
    dynamic_power_W: float = 0.0

class VBWPoint(NamedTuple):
    '''Voltage/bandwidth point for HBM/ICI components.'''
    voltage_V: float = 0.7
    bandwidth_GBs: float = 0.0
    static_power_W: float = 0.0
    dynamic_power_W: float = 0.0

class PowerEfficiencyPoint(NamedTuple):
    '''DVFS voltage regulator power conversion efficiency point for each scaling time, activity factor, and voltage.'''
    scaling_time_ns: int = 0
    activity_factor: float = 1.0
    voltage_V: float = 0.7
    power_efficiency_percent: float = 100.0

